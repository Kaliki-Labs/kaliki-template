// Command new-domain scaffolds the mechanical, non-schema-dependent pieces of
// a new backend (and optionally frontend) domain: a compiling service stub,
// its test skeletons, an empty OpenAPI spec stub, the oapi-codegen wiring for
// that spec, and — if the markers below are still present — the server.go /
// app_router.dart / rest_client_provider.dart auto-wiring.
//
// Usage (run from the project root; this is its own tiny Go module, so -C is
// needed rather than `go run ./scripts/new-domain` — the project root itself
// isn't a Go module):
//
//	go -C scripts/new-domain run . --domain widgets
//	go -C scripts/new-domain run . --domain widgets --api --auth --screen
//	go -C scripts/new-domain run . --domain widgets --no-api
//
// Every interactive question has an equivalent flag so this is fully
// scriptable for AI agents and CI, not just humans at a terminal:
//
//	--domain <name>        lowercase letters, digits, underscores
//	--api / --no-api        does this domain have an API?
//	--auth / --no-auth      does it need auth? (only asked/honored if the
//	                        generated project has auth != none)
//	--screen / --no-screen  add a frontend stub screen? (only asked/honored
//	                        if the generated project has a frontend, and
//	                        only meaningful if the domain has an API)
//
// Any question not answered by a flag is asked interactively. Refuses to run
// if backend/internal/<domain> already exists.
//
// Marker-comment contract: this tool auto-wires three generated files by
// looking for exact marker comments. If a marker is missing (e.g. you edited
// it away), the tool prints the lines to paste manually and exits 0 — it
// never attempts a fuzzy/best-effort insertion:
//
//	backend/internal/server/server.go       // newdomain:imports
//	backend/internal/server/server.go       // newdomain:register
//	frontend/lib/router/app_router.dart     // newdomain:imports
//	frontend/lib/router/app_router.dart     // newdomain:routes
//	frontend/lib/api/rest_client_provider.dart  // newdomain:providers
package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

var domainRe = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

type triState int

const (
	unset triState = iota
	yes
	no
)

func (t triState) bool(def bool) bool {
	switch t {
	case yes:
		return true
	case no:
		return false
	default:
		return def
	}
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func run() error {
	var (
		domainFlag          string
		apiYes, apiNo       bool
		authYes, authNo     bool
		screenYes, screenNo bool
	)
	flag.StringVar(&domainFlag, "domain", "", "domain name (lowercase letters, digits, underscores)")
	flag.BoolVar(&apiYes, "api", false, "this domain has an API (skips the prompt)")
	flag.BoolVar(&apiNo, "no-api", false, "this domain has no API (skips the prompt)")
	flag.BoolVar(&authYes, "auth", false, "this domain's API needs auth (skips the prompt)")
	flag.BoolVar(&authNo, "no-auth", false, "this domain's API is public (skips the prompt)")
	flag.BoolVar(&screenYes, "screen", false, "add a frontend stub screen (skips the prompt)")
	flag.BoolVar(&screenNo, "no-screen", false, "don't add a frontend screen (skips the prompt)")
	flag.Parse()

	if apiYes && apiNo {
		return errors.New("--api and --no-api are mutually exclusive")
	}
	if authYes && authNo {
		return errors.New("--auth and --no-auth are mutually exclusive")
	}
	if screenYes && screenNo {
		return errors.New("--screen and --no-screen are mutually exclusive")
	}

	root, err := findRoot()
	if err != nil {
		return err
	}

	answers, err := loadAnswers(filepath.Join(root, ".copier-answers.yml"))
	if err != nil {
		return fmt.Errorf("reading .copier-answers.yml: %w\n(this tool must be run from a project generated by kaliki-template)", err)
	}
	includeFrontend := answers["include_frontend"] == "true"
	authEnabled := answers["auth"] != "none" && answers["auth"] != ""
	projectName := answers["project_name"]
	if projectName == "" {
		projectName = "API"
	}

	in := bufio.NewReader(os.Stdin)

	domain := domainFlag
	for domain == "" {
		domain = promptLine(in, "Domain name (lowercase letters, digits, underscores): ")
		if !domainRe.MatchString(domain) {
			fmt.Fprintf(os.Stderr, "invalid domain %q: must match ^[a-z][a-z0-9_]*$\n", domain)
			domain = ""
		}
	}
	if !domainRe.MatchString(domain) {
		return fmt.Errorf("invalid --domain %q: must match ^[a-z][a-z0-9_]*$", domain)
	}

	backendDir := filepath.Join(root, "backend")
	domainDir := filepath.Join(backendDir, "internal", domain)
	if _, err := os.Stat(domainDir); err == nil {
		return fmt.Errorf("%s already exists; refusing to overwrite", domainDir)
	}

	hasAPI := resolveTri(apiYes, apiNo)
	if hasAPI == unset {
		hasAPI = boolToTri(promptYesNo(in, "Does "+domain+" have an API?", true))
	}
	apiOn := hasAPI.bool(true)

	authOn := false
	if apiOn && authEnabled {
		t := resolveTri(authYes, authNo)
		if t == unset {
			t = boolToTri(promptYesNo(in, "Does "+domain+" need auth?", false))
		}
		authOn = t.bool(false)
	} else if apiOn && (authYes || authNo) {
		fmt.Fprintln(os.Stderr, "note: project has auth=none; ignoring --auth/--no-auth")
	}

	screenOn := false
	if apiOn && includeFrontend {
		t := resolveTri(screenYes, screenNo)
		if t == unset {
			t = boolToTri(promptYesNo(in, "Add a frontend stub screen for "+domain+"?", false))
		}
		screenOn = t.bool(false)
	} else if (screenYes || screenNo) && !includeFrontend {
		fmt.Fprintln(os.Stderr, "note: project has include_frontend=false; ignoring --screen/--no-screen")
	}

	module, err := readModulePath(filepath.Join(backendDir, "go.mod"))
	if err != nil {
		return err
	}

	if err := os.MkdirAll(domainDir, 0o755); err != nil {
		return err
	}

	if err := writeServiceStub(domainDir, domain); err != nil {
		return err
	}
	if err := writeTestSkeletons(domainDir, domain, module); err != nil {
		return err
	}
	fmt.Printf("scaffolded %s/{service.go,setup_test.go,service_test.go}\n", relPath(root, domainDir))

	if !apiOn {
		fmt.Println("next: no API requested. Implement service.go directly, add a migration, and")
		fmt.Printf("      register '%s.New(pool).Register(api)' in internal/server/server.go.\n", domain)
		return nil
	}

	specPath := filepath.Join(root, "api", "services", domain+".yaml")
	if err := writeSpecStub(specPath, domain, projectName, authOn); err != nil {
		return err
	}
	fmt.Printf("scaffolded %s\n", relPath(root, specPath))

	genDir := filepath.Join(backendDir, "gen", "api", domain)
	if err := os.MkdirAll(genDir, 0o755); err != nil {
		return err
	}
	if err := writeCodegenFiles(genDir, domain); err != nil {
		return err
	}
	fmt.Printf("scaffolded %s/{codegen.yaml,generate.go}\n", relPath(root, genDir))

	fmt.Println("running: go generate ./gen/api/" + domain + "/...")
	cmd := exec.Command("go", "generate", "./gen/api/"+domain+"/...")
	cmd.Dir = backendDir
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("go generate ./gen/api/%s/... failed:\n%s\n%w", domain, out, err)
	}
	if len(strings.TrimSpace(string(out))) > 0 {
		fmt.Println(string(out))
	}

	if err := wireServerGo(filepath.Join(backendDir, "internal", "server", "server.go"), root, domain, module, authOn); err != nil {
		return err
	}

	if screenOn {
		screenDomain := pascalCase(domain)
		screenPath := filepath.Join(root, "frontend", "lib", "screens", domain+"_screen.dart")
		if err := writeScreenStub(screenPath, domain, screenDomain); err != nil {
			return err
		}
		fmt.Printf("scaffolded %s\n", relPath(root, screenPath))

		if err := wireAppRouter(filepath.Join(root, "frontend", "lib", "router", "app_router.dart"), root, domain, screenDomain); err != nil {
			return err
		}
		if err := wireRestClientProvider(filepath.Join(root, "frontend", "lib", "api", "rest_client_provider.dart"), root, domain, screenDomain); err != nil {
			return err
		}
	}

	fmt.Println()
	fmt.Println("next: define real operations in api/services/" + domain + ".yaml, re-run")
	fmt.Println("      'go generate ./gen/api/" + domain + "/...', then implement the handlers in")
	fmt.Printf("      internal/%s/service.go (see internal/items for a worked example if present,\n", domain)
	fmt.Println("      or CLAUDE.md's \"Order of operations for API changes\" section otherwise).")
	return nil
}

func resolveTri(y, n bool) triState {
	if y {
		return yes
	}
	if n {
		return no
	}
	return unset
}

func boolToTri(b bool) triState {
	if b {
		return yes
	}
	return no
}

// findRoot locates the project root (the directory containing both api/ and
// backend/) starting from the current directory and walking upward. This
// tool is meant to be invoked as `go -C scripts/new-domain run .` from the
// project root, but this makes it tolerant of being run from a subdirectory.
func findRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if isDir(filepath.Join(dir, "api")) && isDir(filepath.Join(dir, "backend")) {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("could not locate project root (looking for a directory containing both api/ and backend/); run this from the project root")
		}
		dir = parent
	}
}

func isDir(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.IsDir()
}

func relPath(root, path string) string {
	rel, err := filepath.Rel(root, path)
	if err != nil {
		return path
	}
	return rel
}

func promptLine(in *bufio.Reader, prompt string) string {
	fmt.Print(prompt)
	line, _ := in.ReadString('\n')
	return strings.TrimSpace(line)
}

func promptYesNo(in *bufio.Reader, question string, def bool) bool {
	suffix := "[y/N]"
	if def {
		suffix = "[Y/n]"
	}
	for {
		line := strings.ToLower(promptLine(in, question+" "+suffix+" "))
		switch line {
		case "":
			return def
		case "y", "yes":
			return true
		case "n", "no":
			return false
		}
		fmt.Fprintln(os.Stderr, "please answer y or n")
	}
}

func pascalCase(domain string) string {
	parts := strings.Split(domain, "_")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}

func readModulePath(goModPath string) (string, error) {
	data, err := os.ReadFile(goModPath)
	if err != nil {
		return "", fmt.Errorf("reading %s: %w", goModPath, err)
	}
	for _, line := range strings.Split(string(data), "\n") {
		if after, ok := strings.CutPrefix(line, "module "); ok {
			return strings.TrimSpace(after), nil
		}
	}
	return "", fmt.Errorf("could not find 'module' directive in %s", goModPath)
}
